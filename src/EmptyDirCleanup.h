#pragma once

// 空ディレクトリの自動削除（Issue #33）を、次にファイル一覧のルートを開いたときに
// 走らせるための予約フラグ。
//
// 掃除はSDカード全体の再帰走査になるため、ルートを開くたびに走らせると
// 蔵書が増えるほど表示が遅くなる（Issue #136）。そこで常時ではなく、
// ファイルやディレクトリが実際に消えた／移動したときだけ予約する。
// 起動直後は未掃除とみなすため、初期状態で予約済みになっている。
//
// 予約する側: 本体のファイル操作、Webサーバのファイル管理、WebDAV の DELETE/MOVE
// 消費する側: FileBrowserActivity（ルート表示時、初回描画のあと）

// 次回のルート表示時に掃除を走らせるよう予約する。
void requestEmptyDirCleanup();

// 予約されていれば true を返し、予約を落とす。されていなければ false。
bool consumeEmptyDirCleanupRequest();
